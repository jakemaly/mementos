ok('Source nodes are display-only', !surface.includes('batchCard') || surface.includes('title={batch.query}'));
ok('Batch context shows tool and query', surface.includes('batch.tool'));
ok('Failed batches stay visible with a failure state', surface.includes("batch.status === 'failed'") && surface.includes('failed ·'));
ok('Evidence ranked precedes ingestion', surface.includes('Evidence ranked'));
ok('Ingest Sources stays visibly locked', surface.includes('Locked until the ranked evidence arrives'));
ok('Source register appears only after ranking', surface.includes("ingest.status !== 'locked'"));
ok('Successful import is marked on the destination', surface.includes('Imported ') && surface.includes('ingestResult.totalChunks'));
ok('Import failures stay retryable', surface.includes('review the sources below to retry'));
ok('New research remains available', surface.includes('New research'));
ok('Cancel remains available while running', surface.includes('Cancel'));
ok('Elapsed time stays in the utility strip', surface.includes('Elapsed ') && surface.includes('formatElapsed(elapsedMs)'));
ok('Live status is announced', surface.includes('role="status"') && surface.includes('aria-live="polite"'));
ok('Route summary is announced', surface.includes('traceSummary') && surface.includes('aria-live="polite"'));
