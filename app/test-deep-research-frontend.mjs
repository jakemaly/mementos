ok('Source discovery counts canonical URLs once', traceRoute.includes('canonicalSourceKey'));
ok('Parent pairing lives in the projection', traceModel.includes('pairChildren') && traceModel.includes('parentId'));
ok('Unknown facts are retained', traceModel.includes("kind: 'unknown'") && traceModel.includes('toUnknownFact'));
ok('Calling-card renderer is the existing asset', callingCard.includes('export function drawCallingCardText') && callingCard.includes('export function createCallingCardText'));

console.log('\n=== Trace surface ===\n');
ok('Surface renders the query calling-card artwork', surface.includes('CallingCardArt') && surface.includes('createCallingCardText'));
ok('Artwork is generated once per query', surface.includes('}, [text]);'));
ok('Long queries wrap to a few lines', surface.includes('MAX_QUERY_LINES') && surface.includes('wrapQueryLines'));
ok('Semantic text equivalent stays in the DOM', surface.includes('traceQueryText'));
ok('Brief + Sketch milestone is visible immediately', surface.includes('Brief pending') && surface.includes('Sketch pending'));
ok('Artifact rows resolve independently', surface.includes('Brief created') && surface.includes('Sketch created') && surface.includes('briefCreated') && surface.includes('sketchCreated'));
ok('Pending artifact rows are not actionable', surface.includes('artifactRowPending') && surface.includes('className={`${styles.artifactRow} ${styles.artifactRowPending}`}'));
ok('Created artifact rows are buttons with popover wiring', surface.includes('aria-expanded={openArtifact === \'brief\'}') && surface.includes('aria-controls="brief-popover"'));
