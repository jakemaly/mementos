ok('Sources render inline at the destination, not in a modal', surface.includes('sourceRegister') && !surface.includes('<dialog'));
ok('Register is labelled for assistive tech', surface.includes('aria-label="Ranked sources register"'));
ok('Register appears only when unlocked', surface.includes("ingest.status !== 'locked'"));
ok('Register preserves the existing checklist controls', sources.includes('Select all') && sources.includes('Import selected sources'));
